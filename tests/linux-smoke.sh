#!/usr/bin/env bash
# linux builder 产物冒烟：覆盖 gen --diff-vers（hdiff-sys FFI + libstdc++ 运行时）、
# pack 自提取（不带 --base，验 ELF 内拼接 PE 定位）+ --icon（editpe 资源重写）、
# extract / replace-bin / split。在仓库根目录运行，需先下载 build artifact。
set -euo pipefail

BUILDER="$(pwd)/artifacts/artifact/kachina-builder-linux"
[ -f "$BUILDER" ] || { echo "missing $BUILDER"; exit 1; }
chmod +x "$BUILDER"
SFX="$(pwd)/artifacts/artifact/kachina-sfx.exe"
[ -f "$SFX" ] || { echo "missing $SFX"; exit 1; }
ICON="$(pwd)/resources/icons/icon.ico"

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
cd "$WORK"

# 两版小目录，big.bin 只改少量字节让 hdiff 产出真补丁
mkdir v1 v2
echo hello-v1 > v1/a.txt
echo same > v1/keep.txt
head -c 1500000 /dev/urandom > v1/big.bin
echo hello-v2 > v2/a.txt
echo same > v2/keep.txt
cp v1/big.bin v2/big.bin
printf 'changed' | dd of=v2/big.bin bs=1 seek=100 conv=notrunc 2>/dev/null

echo "== gen v1 =="
"$BUILDER" gen -j 2 -i v1 -m v1-meta.json -o v1-hashed -r SmokeApp -t 1.0.0
echo "== gen v2 --diff-vers v1（hdiff-sys FFI）=="
"$BUILDER" gen -j 2 -i v2 -m v2-meta.json -o v2-hashed -r SmokeApp -t 2.0.0 -d v1
# diff 必须真的产出补丁文件（hash_hash 命名）
ls v2-hashed | grep -q '_' || { echo "no patch files generated by --diff-vers"; exit 1; }

cat > cfg.json <<'EOF'
{"windowTitle": "Smoke", "appName": "Smoke"}
EOF

echo "== pack（自提取 + icon）=="
"$BUILDER" pack -c cfg.json -m v2-meta.json -d v2-hashed --icon "$ICON" -o packed.exe
[ -s packed.exe ] || { echo "packed.exe empty"; exit 1; }

echo "== extract --list / --all =="
"$BUILDER" extract -i packed.exe --list
"$BUILDER" extract -i packed.exe --all extracted
[ -n "$(ls extracted)" ] || { echo "extract produced nothing"; exit 1; }

echo "== replace-bin（自提取）=="
"$BUILDER" replace-bin packed.exe -o replaced.exe
[ -s replaced.exe ] || { echo "replaced.exe empty"; exit 1; }

echo "== replace-bin --base kachina-sfx.exe（便携包路径）=="
"$BUILDER" replace-bin packed.exe --base "$SFX" --icon "$ICON" -o portable.exe
[ -s portable.exe ] || { echo "portable.exe empty"; exit 1; }
# 校验 replace-bin 后载荷完整：extract --list 空载荷也返回成功（只打印表头），
# 且 extract --all 转储的是 zstd 压缩原始块（不解压），无法对照明文源文件。
# 正确口径是逐字节对比 replace 前后两包提取出的全部嵌入块——replace-bin 必须原样保留。
"$BUILDER" extract -i packed.exe --all before-out >/dev/null
"$BUILDER" extract -i portable.exe --all portable-out >/dev/null
diff -r before-out portable-out || { echo "portable.exe payload differs from packed.exe"; exit 1; }
[ -n "$(ls portable-out)" ] || { echo "portable.exe lost embedded payload"; exit 1; }

echo "== split =="
"$BUILDER" split -i packed.exe -o splitout
ls splitout/cas/* >/dev/null 2>&1 || ls splitout | grep -q . || { echo "split produced nothing"; exit 1; }

echo "LINUX SMOKE OK"
